#验证电话号码
import re
test = [
    "13812345678",   # 合法
    "11456817239",   # 非法
    "19912345678",   # 合法
    "17138412356",   # 合法
    "1234567890",    # 非法
    "14752345673",   # 合法
    "1800123456",    # 非法
]
pattern=r"^1[345789]\d{9}$"
for i in test:
    print(f"{i:20}{"合法" if re.match(pattern,i) else "非法"}")